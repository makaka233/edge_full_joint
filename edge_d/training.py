"""Reproducible BUILD-only baseline, no PPO / candidate pool / reward clipping.

One 'update' = one optimizer step trained from `rollouts` complete physical
deployments, NOT a day-scale macro GS. Current PG is a research baseline with
known nontermination and convergence limitations.
"""
from __future__ import annotations
import copy, json, random, time
from dataclasses import asdict, dataclass
from pathlib import Path
import numpy as np
import torch
from torch import nn

from .policy import EditActor
from .world import make_world, observe
from .rollout import sample_layout

@dataclass
class TrainConfig:
    seed:int=20261113
    updates:int=64
    rollouts:int=4
    eval_every:int=8
    fixed_scenes:int=2
    fixed_draws:int=2
    holdout_scenes:int=4
    holdout_draws:int=2
    lr:float=.001
    pg_scale:float=.02
    grad_clip:float=3.
    cpu_finish_guard:bool=True
    max_actions:int=1100
    warmup_seconds:float=20.

def _emit(path:Path,data:dict):
    with path.open("a",encoding="utf8") as fp:
        fp.write(json.dumps(data,ensure_ascii=False,allow_nan=False)+"\n")

def new_actor(seed:int):
    torch.manual_seed(seed+17)
    e=make_world(seed,0,"train")
    return EditActor(observe(e).shape[-1])

def _sample(c:TrainConfig,actor,scene,split,policy_seed,physical_seed,train=False):
    return sample_layout(seed=c.seed,scene=scene,split=split,actor=actor,
                         policy_seed=policy_seed,physical_seed=physical_seed,
                         cpu_finish_guard=c.cpu_finish_guard,
                         warmup_seconds=c.warmup_seconds,max_actions=c.max_actions,train=train)

def evaluate(c:TrainConfig, actor, checkpoint:int, split:str, out:Path|None=None, model_name="last"):
    if split not in ("fixed","holdout"):raise ValueError(split)
    nscenes=c.fixed_scenes if split=="fixed" else c.holdout_scenes
    ndraws=c.fixed_draws if split=="fixed" else c.holdout_draws
    scene0=20 if split=="fixed" else 70
    rows=[]
    with torch.no_grad():
        for z in range(nscenes):
            scene=scene0+z
            for j in range(ndraws):
                ps=c.seed+700000+scene*101+j*409
                ph=c.seed+800000+scene*17+j*101
                row,_=_sample(c,actor,scene,split,ps,ph)
                row.update(update=checkpoint,draw=j,model=model_name)
                rows.append(row)
                if out is not None:_emit(out/"eval.jsonl",row)
    score={
        "seed":c.seed,"update":checkpoint,"split":split,"model":model_name,
        "n":len(rows),"reward":float(np.mean([r["reward"] for r in rows])),
        "e2e":float(np.mean([r["penalized_e2e"] for r in rows])),
        "censored":int(sum(r["censored"] for r in rows)),
        "nonviable":sum(r["cpu_rho_lower_bound"]>=1 for r in rows),
        "mean_actions":float(np.mean([r["decisions"] for r in rows])),
    }
    if out is not None:_emit(out/"eval_summary.jsonl",score)
    return score

def _save(path:Path,actor,optimizer,c:TrainConfig,update:int,best_score:float):
    state={
        "actor_state_dict":actor.state_dict(),
        "optimizer_state_dict":optimizer.state_dict(),
        "config":asdict(c),"update":update,"best_fixed_reward":best_score,
        "torch_rng":torch.get_rng_state(),"numpy_rng":np.random.get_state(),
        "python_rng":random.getstate()
    }
    temp=path.with_suffix(".tmp")
    torch.save(state,temp)
    temp.replace(path)

def load_checkpoint(path:Path):
    # This tool's own checkpoints contain numpy and python RNG states.
    # Only load checkpoints generated by this project, never untrusted ones.
    state=torch.load(path,map_location="cpu",weights_only=False)
    c=TrainConfig(**state["config"])
    actor=new_actor(c.seed)
    actor.load_state_dict(state["actor_state_dict"])
    return c,actor,state

def train(c:TrainConfig,out:Path):
    if c.rollouts<2:raise ValueError("Leave-one-out PG requires >=2 rollouts")
    if c.updates<1 or c.eval_every<1:raise ValueError("Invalid update count")
    out.mkdir(parents=True,exist_ok=True)
    torch.set_num_threads(1)
    random.seed(c.seed);np.random.seed(c.seed)
    actor=new_actor(c.seed)
    opt=torch.optim.Adam(actor.parameters(),lr=c.lr)
    started=time.perf_counter()
    (out/"run_config.json").write_text(json.dumps({**asdict(c),
           "update_unit":"optimizer_updates_not_macro_GS",
           "algorithm":"on_policy_REINFORCE_baseline",
           "physical_reward":"unaltered",
           "selection":"fixed_only",
           "holdout":"start_and_final_only"},indent=2),encoding="utf8")
    best=-float("inf")
    try:
        base=evaluate(c,actor,0,"fixed",out)
        hold0=evaluate(c,actor,0,"holdout",out,model_name="initial")
        best=base["reward"]
        _save(out/"best.pt",actor,opt,c,0,best)
        _save(out/"last.pt",actor,opt,c,0,best)
        for u in range(1,c.updates+1):
            # Known limitation: same demand state within each update.
            scene=(u*7)%61
            batch=[]
            for draw in range(c.rollouts):
                ps=c.seed+10000+u*313+scene*29+draw*1009
                ph=c.seed+20000+u*37+scene*29
                record,logps=_sample(c,actor,scene,"train",ps,ph,train=True)
                record.update(update=u,draw=draw)
                _emit(out/"train.jsonl",record)
                batch.append((record,torch.stack(logps).sum()))
            returns=torch.tensor([x[0]["reward"] for x in batch],dtype=torch.float32)
            advantage=(returns-(returns.sum()-returns)/(len(batch)-1)).detach()
            logps=torch.stack([x[1] for x in batch])
            loss=-c.pg_scale*(advantage*logps).mean()
            opt.zero_grad(set_to_none=True)
            loss.backward()
            grad=float(nn.utils.clip_grad_norm_(actor.parameters(),c.grad_clip,error_if_nonfinite=True))
            opt.step()
            _emit(out/"updates.jsonl",{
                "seed":c.seed,"update":u,"scene":scene,"mean_train_reward":float(returns.mean()),
                "min_train_reward":float(returns.min()),"max_train_reward":float(returns.max()),
                "grad_norm":grad,"loss":float(loss.detach().item()),
                "censored":sum(z["censored"] for z,_ in batch),
                "mean_actions":float(np.mean([z["decisions"] for z,_ in batch])),
                "mean_cpu_rho":float(np.mean([z["cpu_rho_lower_bound"] for z,_ in batch])),
                "elapsed_seconds":time.perf_counter()-started
            })
            # last.pt exists even if a later update fails to terminate.
            _save(out/"last.pt",actor,opt,c,u,best)
            if u%c.eval_every==0 or u==c.updates:
                fixed=evaluate(c,actor,u,"fixed",out)
                if fixed["reward"]>best:
                    best=fixed["reward"]
                    _save(out/"best.pt",actor,opt,c,u,best)
            print(f"seed={c.seed} update={u}/{c.updates} reward={float(returns.mean()):.4f} "
                  f"actions={np.mean([z['decisions'] for z,_ in batch]):.1f}",flush=True)
        for name in ("last","best"):
            ck,act,state=load_checkpoint(out/(name+".pt"))
            final=evaluate(ck,act,c.updates,"holdout",out,model_name=name)
            print("holdout",name,final,flush=True)
        manifest={"status":"completed","completed_updates":c.updates,
                  "elapsed_seconds":time.perf_counter()-started,
                  "initial_holdout":hold0}
        (out/"manifest.json").write_text(json.dumps(manifest,indent=2),encoding="utf8")
        return manifest
    except Exception as error:
        _emit(out/"failures.jsonl",{
            "seed":c.seed,"status":"aborted_without_fabricated_reward",
            "error":repr(error),"time":time.time()
        })
        (out/"manifest.json").write_text(json.dumps({
            "status":"aborted","error":repr(error),
            "elapsed_seconds":time.perf_counter()-started},indent=2),encoding="utf8")
        raise
